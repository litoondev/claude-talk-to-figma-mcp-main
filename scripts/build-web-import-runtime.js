#!/usr/bin/env node
/**
 * Copy the Web-to-Figma import runtime to where each caller loads it.
 *
 * src/web_import/runtime.js is the only copy anyone edits. It is not part of
 * the Figma plugin: callers send it with each import through the plugin's
 * execute_code command, so the plugin's code.js never changes for it.
 *
 *   src/talk_to_figma_mcp/web-import/runtime.generated.ts  MCP server and relay
 *   browser_extension/web-import-runtime.js               Chrome extension
 *
 * Run by `npm run build`. tests/unit/web-import-runtime.test.ts fails when a
 * copy is out of date.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const SOURCE = path.join(ROOT, "src", "web_import", "runtime.js");
const TS_OUT = path.join(ROOT, "src", "talk_to_figma_mcp", "web-import", "runtime.generated.ts");
const EXT_OUT = path.join(ROOT, "browser_extension", "web-import-runtime.js");

export function render(source) {
  return {
    ts:
      "// GENERATED by scripts/build-web-import-runtime.js from src/web_import/runtime.js — do not edit.\n" +
      "export const WEB_IMPORT_RUNTIME: string = " + JSON.stringify(source) + ";\n",
    ext: "// GENERATED by scripts/build-web-import-runtime.js from src/web_import/runtime.js — do not edit.\n" + source,
  };
}

const source = fs.readFileSync(SOURCE, "utf8");
const out = render(source);
let changed = 0;
for (const [file, text] of [[TS_OUT, out.ts], [EXT_OUT, out.ext]]) {
  if (!fs.existsSync(file) || fs.readFileSync(file, "utf8") !== text) {
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, text);
    changed++;
  }
}
console.log(`web import runtime: ${changed ? `${changed} copy(ies) updated` : "copies already current"}`);

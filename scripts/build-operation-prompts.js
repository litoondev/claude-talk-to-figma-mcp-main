#!/usr/bin/env node
/**
 * Inject the operation prompts into the plugin UIs.
 *
 * A Figma plugin UI is one self-contained HTML file — it cannot require a
 * module at runtime — so the prompts have to be inlined. Rather than keep three
 * hand-maintained copies that drift (which is how they ended up as one-line
 * stubs), the list lives in `src/claude_mcp_plugin/operation-prompts.js` and
 * this script writes it into the generated block of each UI file.
 *
 * Run by `npm run build`. Safe to run repeatedly; it rewrites only the block
 * between the START/END markers.
 */

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

import { OPERATION_PROMPTS } from "../src/claude_mcp_plugin/operation-prompts.js";

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const START = "/* OPERATION_PROMPTS:START";
const END = "/* OPERATION_PROMPTS:END */";

const TARGETS = [
  { file: "src/claude_mcp_plugin/ui.html", indent: "        " },
  { file: "src/claude_mcp_plugin/ui-v2.html", indent: "                " },
  { file: "src/claude_mcp_plugin/operations-menu.js", indent: "    " },
];

function validate(operations) {
  const seen = new Set();
  for (const op of operations) {
    for (const field of ["id", "category", "title", "description", "prompt"]) {
      if (typeof op[field] !== "string" || !op[field].trim()) {
        throw new Error(`operation "${op.id || "?"}" is missing ${field}`);
      }
    }
    if (seen.has(op.id)) throw new Error(`duplicate operation id: ${op.id}`);
    seen.add(op.id);

    // A stub prompt is the bug this file exists to prevent, so fail the build
    // rather than ship one.
    if (op.prompt.length < 600) {
      throw new Error(`prompt for "${op.id}" is too short to stand on its own (${op.prompt.length} chars)`);
    }
    if (!op.prompt.includes("join_channel")) {
      throw new Error(`prompt for "${op.id}" never connects to Figma (no join_channel)`);
    }
  }
  return operations;
}

function render(operations, indent) {
  const body = JSON.stringify(operations, null, 2)
    .split("\n")
    .map((line) => indent + line)
    .join("\n")
    .trimStart();

  return [
    `${indent}${START} — generated by scripts/build-operation-prompts.js; do not edit by hand */`,
    `${indent}const OPERATION_PROMPTS = ${body};`,
    `${indent}${END}`,
  ].join("\n");
}

function inject(target, operations) {
  const file = path.join(ROOT, target.file);
  const contents = fs.readFileSync(file, "utf8");

  const start = contents.indexOf(START);
  const end = contents.indexOf(END);
  if (start === -1 || end === -1 || end < start) {
    throw new Error(`${target.file} has no OPERATION_PROMPTS block — add the START/END markers back`);
  }

  const lineStart = contents.lastIndexOf("\n", start) + 1;
  const next = render(operations, target.indent);
  const updated = contents.slice(0, lineStart) + next + contents.slice(end + END.length);

  if (updated === contents) return false;
  fs.writeFileSync(file, updated);
  return true;
}

const operations = validate(OPERATION_PROMPTS);
const changed = TARGETS.filter((target) => inject(target, operations));

console.log(
  `operations: ${operations.length} prompt(s) injected into ${TARGETS.length} UI file(s)` +
    (changed.length ? ` — updated ${changed.map((t) => path.basename(t.file)).join(", ")}` : " — already current")
);
